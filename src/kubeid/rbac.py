# ABOUTME: Renders Kubernetes RBAC manifests from kubeid config: issuer identity and group bindings.
# ABOUTME: Output is plain YAML meant to be committed to Git and applied with kubectl.
import yaml

from kubeid.kube import SIGNER_NAME

NAMESPACE = "kubeid"
ISSUER_SA = "kubeid-issuer"
ISSUER_TOKEN_SECRET = "kubeid-issuer-token"
ISSUER_ROLE = "kubeid:issuer"
RBAC_API = "rbac.authorization.k8s.io"
LABELS = {"app.kubernetes.io/managed-by": "kubeid"}


def _meta(name, namespace=None, annotations=None):
    meta = {"name": name}
    if namespace is not None:
        meta["namespace"] = namespace
    meta["labels"] = dict(LABELS)
    if annotations:
        meta["annotations"] = annotations
    return meta


def _clusterrole_ref(name):
    return {"apiGroup": RBAC_API, "kind": "ClusterRole", "name": name}


def issuer_manifests():
    """Identity kubeid itself uses: may create and approve client-cert CSRs, nothing else."""
    return [
        {"apiVersion": "v1", "kind": "Namespace", "metadata": _meta(NAMESPACE)},
        {"apiVersion": "v1", "kind": "ServiceAccount", "metadata": _meta(ISSUER_SA, NAMESPACE)},
        {
            "apiVersion": "v1",
            "kind": "Secret",
            "type": "kubernetes.io/service-account-token",
            "metadata": _meta(
                ISSUER_TOKEN_SECRET,
                NAMESPACE,
                annotations={"kubernetes.io/service-account.name": ISSUER_SA},
            ),
        },
        {
            "apiVersion": f"{RBAC_API}/v1",
            "kind": "ClusterRole",
            "metadata": _meta(ISSUER_ROLE),
            "rules": [
                {
                    "apiGroups": ["certificates.k8s.io"],
                    "resources": ["certificatesigningrequests"],
                    "verbs": ["create", "get"],
                },
                {
                    "apiGroups": ["certificates.k8s.io"],
                    "resources": ["certificatesigningrequests/approval"],
                    "verbs": ["update"],
                },
                {
                    "apiGroups": ["certificates.k8s.io"],
                    "resources": ["signers"],
                    "resourceNames": [SIGNER_NAME],
                    "verbs": ["approve"],
                },
            ],
        },
        {
            "apiVersion": f"{RBAC_API}/v1",
            "kind": "ClusterRoleBinding",
            "metadata": _meta(ISSUER_ROLE),
            "roleRef": _clusterrole_ref(ISSUER_ROLE),
            "subjects": [{"kind": "ServiceAccount", "name": ISSUER_SA, "namespace": NAMESPACE}],
        },
    ]


def binding_manifests(config):
    docs = []
    for rule in config.rbac:
        name = f"kubeid:{rule.group}:{rule.clusterrole}"
        subjects = [{"kind": "Group", "name": rule.group, "apiGroup": RBAC_API}]
        if not rule.namespaces:
            docs.append(
                {
                    "apiVersion": f"{RBAC_API}/v1",
                    "kind": "ClusterRoleBinding",
                    "metadata": _meta(name),
                    "roleRef": _clusterrole_ref(rule.clusterrole),
                    "subjects": subjects,
                }
            )
        for namespace in rule.namespaces:
            docs.append(
                {
                    "apiVersion": f"{RBAC_API}/v1",
                    "kind": "RoleBinding",
                    "metadata": _meta(name, namespace),
                    "roleRef": _clusterrole_ref(rule.clusterrole),
                    "subjects": subjects,
                }
            )
    return docs


def render_manifests(config):
    return issuer_manifests() + binding_manifests(config)


def render_yaml(config):
    header = "# Generated by `kubeid rbac`. Commit to Git, then: kubectl apply -f <this file>\n"
    return header + yaml.safe_dump_all(render_manifests(config), sort_keys=False, explicit_start=True)
